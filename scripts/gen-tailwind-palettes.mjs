// Generates src/lib/tailwind-palettes.ts.
//
// Tailwind v3 colors come from the installed `tailwindcss` package. Tailwind
// v4 isn't installed (the extension builds with v3), so pass its theme.css and
// version, e.g. from https://unpkg.com/tailwindcss@4.3.3/theme.css:
//
//   node scripts/gen-tailwind-palettes.mjs path/to/theme.css 4.3.3

import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const [themeCssPath, v4Version] = process.argv.slice(2)
if (!themeCssPath || !v4Version) {
  console.error(
    "Usage: node scripts/gen-tailwind-palettes.mjs <v4 theme.css> <v4 version>"
  )
  process.exit(1)
}

const require = createRequire(import.meta.url)
const v3Colors = require("tailwindcss/colors")
const v3Version = require("tailwindcss/package.json").version

const v3 = {}
for (const name of Object.keys(v3Colors)) {
  // Renamed palettes (lightBlue, warmGray...) are getters that log a warning
  if (Object.getOwnPropertyDescriptor(v3Colors, name).get) continue
  const value = v3Colors[name]
  if (typeof value === "string") {
    if (value.startsWith("#")) v3[name] = value
  } else {
    for (const [shade, hex] of Object.entries(value))
      v3[`${name}-${shade}`] = hex
  }
}

const v4 = {}
const css = readFileSync(themeCssPath, "utf8")
for (const [, name, value] of css.matchAll(
  /--color-([a-z]+(?:-\d+)?):\s*([^;]+);/g
)) {
  v4[name] = value.trim()
}

// Palette order as in the source, shades in numeric order
const sortEntries = (palette) => {
  const order = [
    ...new Set(Object.keys(palette).map((key) => key.split("-")[0]))
  ]
  return Object.entries(palette).sort(([a], [b]) => {
    const [nameA, shadeA = "0"] = a.split("-")
    const [nameB, shadeB = "0"] = b.split("-")
    return (
      order.indexOf(nameA) - order.indexOf(nameB) ||
      Number(shadeA) - Number(shadeB)
    )
  })
}

const toObjectLiteral = (palette) =>
  sortEntries(palette)
    .map(([name, value]) => `  "${name}": "${value}"`)
    .join(",\n")

const output = `// Generated by scripts/gen-tailwind-palettes.mjs. Don't edit by hand.
// Tailwind CSS v${v3Version} (hex) and v${v4Version} (as written in its theme.css)

export const TAILWIND_V3_VERSION = "${v3Version}"
export const TAILWIND_V4_VERSION = "${v4Version}"

export const TAILWIND_V3: Record<string, string> = {
${toObjectLiteral(v3)}
}

export const TAILWIND_V4: Record<string, string> = {
${toObjectLiteral(v4)}
}
`

writeFileSync(
  new URL("../src/lib/tailwind-palettes.ts", import.meta.url),
  output
)
console.log(
  `Wrote ${Object.keys(v3).length} v${v3Version} and ${Object.keys(v4).length} v${v4Version} colors`
)
